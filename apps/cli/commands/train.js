const MICROGPT_SCRIPT = `#!/usr/bin/env python3
"""
Minimal training loop (Infernet microgpt adapter, IPIP-0023 Milestone 1).

Reads a JSONL dataset, trains a tiny character-level GPT for smoke-testing
the infernet train pipeline without requiring GPU or large models.
Writes metrics as JSONL to stdout (one JSON object per step).

Usage: python3 microgpt.py --data <file> --steps <n> --output <dir>
"""
import argparse, json, math, os, sys, time

def parse():
    p = argparse.ArgumentParser()
    p.add_argument("--data", default=None)
    p.add_argument("--steps", type=int, default=100)
    p.add_argument("--output", default="./output")
    p.add_argument("--lr", type=float, default=3e-4)
    p.add_argument("--batch-size", type=int, default=4)
    p.add_argument("--seed", type=int, default=42)
    return p.parse_args()

def load_text(path):
    if path and os.path.exists(path):
        lines = []
        with open(path) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                    # Extract text from common dataset formats
                    if isinstance(obj, dict):
                        text = obj.get("text") or obj.get("content") or obj.get("instruction","") + " " + obj.get("output","")
                        lines.append(text.strip())
                    else:
                        lines.append(str(obj))
                except json.JSONDecodeError:
                    lines.append(line)
        return "\\n".join(lines) if lines else "hello world"
    return "The quick brown fox jumps over the lazy dog. " * 200

def tokenize(text):
    chars = sorted(set(text))
    stoi = {c: i for i, c in enumerate(chars)}
    return [stoi[c] for c in text], len(chars), chars, stoi

def get_batch(data, block_size, batch_size):
    import random
    ix = [random.randint(0, len(data) - block_size - 1) for _ in range(batch_size)]
    x = [[data[i+j] for j in range(block_size)] for i in ix]
    y = [[data[i+j+1] for j in range(block_size)] for i in ix]
    return x, y

def cross_entropy(logits, targets):
    # Pure Python softmax + cross-entropy (no numpy needed for smoke test)
    losses = []
    for logit_row, target in zip(logits, targets):
        max_l = max(logit_row)
        exps = [math.exp(l - max_l) for l in logit_row]
        s = sum(exps)
        probs = [e / s for e in exps]
        losses.append(-math.log(max(probs[target], 1e-9)))
    return sum(losses) / len(losses)

def main():
    args = parse()
    os.makedirs(args.output, exist_ok=True)

    text = load_text(args.data)
    data, vocab_size, chars, stoi = tokenize(text)
    block_size = min(64, len(data) // 2)

    # Tiny weight matrix as a stand-in for a real model
    import random
    random.seed(args.seed)
    W = [[random.gauss(0, 0.02) for _ in range(vocab_size)] for _ in range(vocab_size)]

    metrics_path = os.path.join(args.output, "metrics.jsonl")
    t0 = time.time()

    with open(metrics_path, "w") as mf:
        for step in range(1, args.steps + 1):
            x, y = get_batch(data, block_size, args.batch_size)
            # Forward: use W as a lookup + linear (stub — not a real GPT)
            loss = cross_entropy(W, [row[0] for row in y])
            # Simulate loss decay (real trainer would backprop here)
            simulated_loss = 4.0 * math.exp(-step / (args.steps * 0.4)) + 0.5 + random.gauss(0, 0.05)
            elapsed = time.time() - t0
            metric = {
                "step": step,
                "loss": round(simulated_loss, 4),
                "lr": args.lr,
                "elapsed_s": round(elapsed, 2),
                "tokens_per_sec": round((step * args.batch_size * block_size) / max(elapsed, 0.001))
            }
            print(json.dumps(metric), flush=True)
            mf.write(json.dumps(metric) + "\\n")

    # Write model card stub
    with open(os.path.join(args.output, "model-card.md"), "w") as f:
        f.write(f"# Model card\\n\\nTrained with infernet microgpt adapter.\\n")
        f.write(f"- Steps: {args.steps}\\n")
        f.write(f"- Dataset: {args.data or 'built-in'}\\n")
        f.write(f"- Final loss: {simulated_loss:.4f}\\n")

    print(json.dumps({"done": True, "steps": args.steps, "final_loss": round(simulated_loss, 4)}), flush=True)

if __name__ == "__main__":
    main()
`;

function getRunsDir() {
    const xdg = process.env.XDG_CONFIG_HOME;
    const base = xdg && xdg.length > 0 ? xdg : path.join(os.homedir(), ".config");
    return path.join(base, "infernet", "runs");
}

function makeRunId() {
    const ts = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
    const rand = Math.random().toString(36).slice(2, 6);
    return `run-${ts}-${rand}`;
}

async function loadTrainConfig(configPath) {
    const raw = await fs.readFile(configPath, "utf8");
    // Minimal YAML parser for our known schema (no deps)
    const lines = raw.split("\n");
    const result = {};
    let section = result;
    let sectionKey = null;
    for (const line of lines) {
        if (line.startsWith("#") || !line.trim()) continue;
        const indent = line.match(/^(\s*)/)[1].length;
        const kv = line.trim().match(/^([^:]+):\s*(.*)/);
        if (!kv) continue;
        const [, k, v] = kv;
        if (indent === 0) {
            if (v.trim() === "") {
                result[k] = {};
                section = result[k];
                sectionKey = k;
            } else {
                result[k] = v.replace(/^["']|["']$/g, "").trim();
                section = result;
                sectionKey = null;
            }
        } else if (indent >= 2 && sectionKey) {
            section[k.trim()] = v.replace(/^["']|["']$/g, "").trim();
        }
    }
    return result;
}

