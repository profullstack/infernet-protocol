/**
 * `infernet train` — distributed training + fine-tuning (IPIP-0023).
 *
 * Milestone 1: CLI skeleton + local microgpt mode.
 *   infernet train init   — scaffold infernet.train.yml
 *   infernet train run    — run training locally or submit to P2P
 *   infernet train status — show run status
 *   infernet train list   — list runs
 *   infernet train logs   — tail run logs
 *
 * Local mode (--local or workload_class: C1 + no live provider) runs a
 * minimal Python training loop using the bundled microgpt adapter, writes
 * run-wiki artifacts (config.yml, metrics.jsonl, README.md) to --output.
 */

